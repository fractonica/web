/*
 * The C type of a field as one letter (the letters of Python's `struct`):
 *   B u8   b i8   H u16   h i16   I u32   i i32   Q u64   q i64   f float
 *   P a pointer (frc_catalogue_t.instants_ms)   T a nested frc_threshold_t
 * A field of any other type does not compile: add its letter here and its
 * reader in fractonica.js.
 */
#define FRCW_TYPE(expr) _Generic((expr), \
    uint8_t: 'B', int8_t: 'b', uint16_t: 'H', int16_t: 'h', \
    uint32_t: 'I', int32_t: 'i', uint64_t: 'Q', int64_t: 'q', \
    float: 'f', const int64_t *: 'P', frc_threshold_t: 'T')

#define FRCW_STRUCT_MARK 0xFFFFu

/* Numbers: per struct  MARK, sizeof, alignof;  per field  offset, type letter, element count. */
#define FRCW_S_NUM(T)    FRCW_STRUCT_MARK, sizeof(T), _Alignof(T),
#define FRCW_F_NUM(T, f) offsetof(T, f), FRCW_TYPE(((T *)0)->f), 1,
#define FRCW_A_NUM(T, f) offsetof(T, f), FRCW_TYPE(((T *)0)->f[0]), \
